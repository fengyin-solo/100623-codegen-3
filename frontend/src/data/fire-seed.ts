/** 当前时间往前/后偏移天数，返回 YYYY-MM-DD，种子数据始终贴近"今天"。 */
function dayOffset(days: number): string {
  const d = new Date()
  d.setDate(d.getDate() + days)
  return d.toISOString().slice(0, 10)
}

function nowStamp(): string {
  return new Date().toISOString().slice(0, 16)
}

